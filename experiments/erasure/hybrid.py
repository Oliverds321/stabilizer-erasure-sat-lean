"""A practical two-tail estimator built on the same Bad certificate.

The algorithm of the main theorem treats every layer with hashing and a SAT
oracle. For codes beyond the reach of an off-the-shelf hashing counter this
module uses the SAT oracle only where sampling cannot work:

  low layers   Every uncorrectable set contains an inclusion-minimal one. A SAT
               solver enumerates *all* minimal uncorrectable sets of size
               1, 2, ..., w (each level ends with an UNSAT answer, which
               certifies completeness). Verified qubit permutations that
               preserve the stabilizer space (translations of toric and
               bivariate bicycle codes) are used to search only for sets
               through one representative qubit per orbit and to add whole
               orbits at once. For j <= w the layer sums are then estimated by
               Karp-Luby sampling over the union of the supersets of the listed
               sets, an unbiased estimator whose relative variance does not
               grow as uncorrectable sets become rare.
  next layers  For j slightly above w uniform sampling still sees too few
               uncorrectable sets. The layer sum is split into the sets that
               contain a listed minimal set (Karp-Luby again; the identity
               holds for any j) and the remainder, the uncorrectable sets that
               contain none; only the remainder is sampled.
  bulk layers  Uniform sampling of erased sets of size j.

Every layer returns estimates of f_j (mean of 2^{-d_E}), b_j = 1 - f_j and
u_j (uncorrectable fraction) with standard errors. Since the curves are
positive combinations of the coefficients, the relative error of I(p), F(p)
and U(p) at every p is at most the largest coefficient-wise relative error.

The same enumeration applied to the complement (duality d_E + d_{E^c} = 2k)
handles the high layers of the fidelity side: f_j 4^k - 1 is the mean of
2^{d_E'} - 1 over sets E' of size n - j, which vanishes on correctable E'.
"""
import json
import os
import time
from math import comb
from pathlib import Path

import numpy as np
from numba import njit, prange

import qec_codes
from gf2 import pack_rows, full_mask, exponent, exponent_of, sample_layer

HERE = Path(__file__).resolve().parent
SOLVER_THREADS = int(os.environ.get("SAT_THREADS", "1"))  # CryptoMiniSat threads per search


# ---------------------------------------------------------------- SAT side

def _logical_formula(code):
    """x in N, supp(x) inside E, x not in S (anticommutes with a logical)."""
    from certificates import Formula, _normalizer_constraints
    n = code.n
    f = Formula()
    e = f.new(n)
    xx, xz = f.new(n), f.new(n)
    _normalizer_constraints(f, code, xx, xz)
    for i in range(n):
        f.add(-xx[i], e[i])
        f.add(-xz[i], e[i])
    basis = code.logical_basis()
    hits = []
    for row in basis:  # symplectic pairing of x with the logical operator `row`
        lits = [xz[i] for i in range(n) if row[i]] + [xx[i] for i in range(n) if row[n + i]]
        t = f.xor_chain(lits)
        if t is not None:
            hits.append(t)
    f.add_split(hits)
    return f, e


def symmetry_group(code):
    """Qubit permutations generated by `code.generators`, each verified to
    preserve the stabilizer space; returns the list of group elements."""
    from gf2 import rank_dense
    n = code.n
    identity = tuple(range(n))
    gens = []
    for g in code.generators:
        g = tuple(int(x) for x in g)
        assert sorted(g) == list(range(n))
        moved = np.zeros_like(code.h)
        for i in range(n):  # column i of the permuted matrix sits at g[i]
            moved[:, g[i]] = code.h[:, i]
            moved[:, n + g[i]] = code.h[:, n + i]
        if rank_dense(np.concatenate([code.h, moved])) != code.s:
            raise ValueError("a generator does not preserve the stabilizer space")
        gens.append(g)
    group, frontier = {identity}, [identity]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = tuple(g[i] for i in x)
                if y not in group:
                    group.add(y)
                    new.append(y)
        frontier = new
    return sorted(group)


def _orbit_representatives(n, group):
    seen, reps = set(), []
    for q in range(n):
        if q not in seen:
            reps.append(q)
            seen.update(g[q] for g in group)
    return reps


def _level_search(args):
    """All minimal uncorrectable sets of size w through qubit q (any set if q is None).

    Returns the list found, closed under the group, or None on timeout.
    """
    from pycryptosat import Solver
    from pysat.card import CardEnc, EncType
    name, w, q, found, deadline = args
    code = qec_codes.get(name)
    n = code.n
    group = symmetry_group(code)
    f, e = _logical_formula(code)
    enc = CardEnc.atmost(lits=e, bound=w, top_id=f.nvars, encoding=EncType.totalizer)
    solver = Solver(threads=SOLVER_THREADS)
    solver.add_clauses(f.clauses)
    solver.add_clauses(enc.clauses)
    if q is not None:  # every nonempty set has a translate through a representative
        solver.add_clause([e[q]])
    for m in found:
        solver.add_clause([-e[i] for i in m])
    level = set()
    while True:
        left = deadline - time.time()
        if left <= 0:
            return None
        sat, model = solver.solve(time_limit=left)
        if sat is None:
            return None
        if not sat:
            return sorted(level)
        m = tuple(i for i in range(n) if model[e[i]])
        # all smaller minimal sets are blocked, so m is minimal and |m| = w
        assert len(m) == w
        for g in group:
            image = tuple(sorted(g[i] for i in m))
            if image not in level:
                level.add(image)
                solver.add_clause([-e[i] for i in image])


def minimal_sets(code, max_size, max_count=2_000_000, time_limit=3600.0, log=print,
                 cache=None, use_symmetry=True, name=None):
    """All inclusion-minimal uncorrectable sets of size <= max_size, level by level.

    Returns (list of sorted tuples, largest level proved complete). Only
    complete levels are returned. With `cache` (a path) finished levels are
    stored and reused. With `name` (a key of qec_codes.REGISTRY) and a
    nontrivial symmetry group, the searches through the orbit representatives
    of one level run in parallel processes.
    """
    from concurrent.futures import ProcessPoolExecutor
    n = code.n
    group = symmetry_group(code) if use_symmetry else [tuple(range(n))]
    reps = _orbit_representatives(n, group) if len(group) > 1 else [None]
    found, complete = [], 0
    if cache is not None and Path(cache).exists():
        data = json.loads(Path(cache).read_text())
        found, complete = [tuple(m) for m in data["sets"]], data["complete"]
        log(f"  cache: {len(found)} minimal sets, complete through size {complete}")
    start = time.time()
    deadline = start + time_limit
    parallel = name is not None and len(reps) > 1
    pool = ProcessPoolExecutor(max_workers=len(reps)) if parallel else None
    try:
        for w in range(complete + 1, max_size + 1):
            if not use_symmetry:
                # plain search, kept for cross-checking the symmetric one
                results = [_plain_level(code, w, found, deadline)]
            elif parallel:
                results = list(pool.map(_level_search,
                                        [(name, w, q, found, deadline) for q in reps]))
            else:
                key = name if name is not None else _register_temp(code)
                results = [_level_search((key, w, q, found, deadline)) for q in reps]
            if any(r is None for r in results):
                log(f"  level {w}: time limit, incomplete (discarded)")
                break
            level = sorted(set(m for r in results for m in r))
            if len(found) + len(level) > max_count:
                log(f"  level {w}: {len(level)} sets exceed the cap (discarded)")
                break
            found.extend(level)
            complete = w
            log(f"  level {w}: {len(level)} minimal sets, complete ({time.time() - start:.0f}s)")
            if cache is not None:
                Path(cache).write_text(json.dumps({"complete": complete, "sets": found}))
    finally:
        if pool is not None:
            pool.shutdown(cancel_futures=True)
    return found, complete


def _register_temp(code):
    """Make an unregistered code reachable by name for `_level_search`."""
    key = f"_tmp_{id(code)}"
    qec_codes.REGISTRY[key] = lambda: code
    return key


def _plain_level(code, w, found, deadline):
    from pycryptosat import Solver
    from pysat.card import CardEnc, EncType
    f, e = _logical_formula(code)
    solver = Solver(threads=1)
    solver.add_clauses(f.clauses)
    solver.add_clauses(CardEnc.atmost(lits=e, bound=w, top_id=f.nvars,
                                      encoding=EncType.totalizer).clauses)
    for m in found:
        solver.add_clause([-e[i] for i in m])
    level = []
    while True:
        left = deadline - time.time()
        if left <= 0:
            return None
        sat, model = solver.solve(time_limit=left)
        if sat is None:
            return None
        if not sat:
            return level
        m = tuple(i for i in range(code.n) if model[e[i]])
        assert len(m) == w
        level.append(m)
        solver.add_clause([-e[i] for i in m])


# ------------------------------------------------------------ Karp-Luby side

def _masks(sets, n):
    words = (n + 63) // 64
    out = np.zeros((len(sets), words), dtype=np.uint64)
    for idx, m in enumerate(sets):
        for i in m:
            out[idx, i // 64] |= np.uint64(1) << np.uint64(i % 64)
    return out


@njit(parallel=True, cache=True)
def _karp_luby(rows, n, s, full, mins, sizes, cum, j, samples, threads, seed):
    """Sums and sums of squares of g(E)/N(E) for g in {1, 1-2^-d, 2^d-1}."""
    t = mins.shape[0]
    words = mins.shape[1]
    acc = np.zeros((threads, 6), dtype=np.float64)
    per = samples // threads
    for th in prange(threads):
        np.random.seed(seed + 9973 * th + 31337 * j)
        mask = np.zeros(rows.shape[1], dtype=np.uint64)
        work = np.zeros_like(rows)
        erased = np.zeros(n, dtype=np.uint8)
        emask = np.zeros(words, dtype=np.uint64)
        rest = np.zeros(n, dtype=np.int64)
        for _ in range(per):
            r = np.random.random()
            lo, hi = 0, t - 1
            while lo < hi:  # first index with cum >= r
                mid = (lo + hi) // 2
                if cum[mid] >= r:
                    hi = mid
                else:
                    lo = mid + 1
            term = lo
            cnt = 0
            for i in range(n):
                bit = (mins[term, i // 64] >> np.uint64(i % 64)) & np.uint64(1)
                erased[i] = bit
                if not bit:
                    rest[cnt] = i
                    cnt += 1
            extra = j - sizes[term]
            for a in range(extra):
                b = a + np.random.randint(0, cnt - a)
                tmp = rest[a]
                rest[a] = rest[b]
                rest[b] = tmp
                erased[rest[a]] = 1
            for w in range(words):
                emask[w] = 0
            for i in range(n):
                if erased[i]:
                    emask[i // 64] |= np.uint64(1) << np.uint64(i % 64)
            mult = 0
            for l in range(t):
                inside = True
                for w in range(words):
                    if mins[l, w] & ~emask[w]:
                        inside = False
                        break
                if inside:
                    mult += 1
            d = exponent(rows, n, s, erased, mask, full, work)
            g0 = 1.0 / mult
            g1 = (1.0 - 2.0 ** (-d)) / mult
            g2 = (2.0 ** d - 1.0) / mult
            acc[th, 0] += g0
            acc[th, 1] += g0 * g0
            acc[th, 2] += g1
            acc[th, 3] += g1 * g1
            acc[th, 4] += g2
            acc[th, 5] += g2 * g2
    return acc.sum(axis=0), per * threads


def karp_luby_layer(code, mins, j, samples=200_000, threads=8, seed=1):
    """Layer averages of (uncorrectable, 1-2^-d, 2^d-1) over |E| = j, with standard errors.

    `mins` must contain every minimal uncorrectable set of size <= j.
    """
    n = code.n
    usable = [m for m in mins if len(m) <= j]
    if not usable:
        return {"u": (0.0, 0.0), "b": (0.0, 0.0), "dual": (0.0, 0.0), "terms": 0}
    weights = np.array([float(comb(n - len(m), j - len(m))) for m in usable])
    total = float(sum(comb(n - len(m), j - len(m)) for m in usable))
    cum = np.cumsum(weights / weights.sum())
    cum[-1] = 1.0
    sums, count = _karp_luby(pack_rows(code.h), n, code.s, full_mask(n), _masks(usable, n),
                             np.array([len(m) for m in usable], dtype=np.int64), cum, j,
                             samples, threads, seed)
    scale = total / comb(n, j)
    out = {"terms": len(usable)}
    for key, a in (("u", 0), ("b", 2), ("dual", 4)):
        mean = sums[a] / count
        var = max(sums[a + 1] / count - mean * mean, 0.0) / count
        out[key] = (mean * scale, var ** 0.5 * scale)
    return out


def exact_first_layer(code, mins, j):
    """Exact layer averages at the smallest size j of a listed set.

    When the list is complete through size j and has no smaller set, the
    uncorrectable sets of size j are exactly the listed sets of size j, so the
    layer sums are finite sums over the list (no sampling).
    """
    assert all(len(m) >= j for m in mins)
    ds = [exponent_of(code, m) for m in mins if len(m) == j]
    c = comb(code.n, j)
    return {"terms": len(ds), "exact": True,
            "by_exponent": {str(d): ds.count(d) for d in sorted(set(ds))},
            "u": (len(ds) / c, 0.0),
            "b": (sum(1 - 2.0 ** (-d) for d in ds) / c, 0.0),
            "dual": (sum(2.0 ** d - 1 for d in ds) / c, 0.0)}


# ------------------------------------------------------------ sampling side

def sampled_layer(code, j, samples, threads=8, seed=1, target_events=0, max_samples=0):
    """Layer averages (f, b, u) with standard errors from uniform sampling.

    With `target_events` = T, keep tripling the sample until the relative
    standard errors of both f_j and b_j are below 1/sqrt(T) (the error of a
    count of T events), or `max_samples` is reached.
    """
    def rel_errors(h):
        c = h.sum()
        dd = np.arange(len(h))
        worst = 0.0
        for g in (2.0 ** (-dd), 1 - 2.0 ** (-dd)):
            mean = (h * g).sum() / c
            if mean <= 0:
                return float("inf")
            var = max((h * g * g).sum() / c - mean * mean, 0.0) / c
            worst = max(worst, var ** 0.5 / mean)
        return worst

    hist = sample_layer(code, j, samples, threads=threads, seed=seed).astype(np.float64)
    rounds = 1
    while target_events and hist.sum() < max_samples and rel_errors(hist) > target_events ** -0.5:
        batch = int(min(2 * hist.sum(), max_samples - hist.sum()))
        if batch < threads:
            break
        hist += sample_layer(code, j, batch, threads=threads, seed=seed + 1000 * rounds)
        rounds += 1
    count = hist.sum()
    d = np.arange(len(hist))
    out = {"events": int(hist[1:].sum()), "samples": int(count)}
    for key, g in (("f", 2.0 ** (-d)), ("b", 1 - 2.0 ** (-d)), ("u", (d > 0).astype(float))):
        mean = float((hist * g).sum() / count)
        var = max(float((hist * g * g).sum() / count) - mean * mean, 0.0) / count
        out[key] = (mean, var ** 0.5)
    return out


@njit(parallel=True, cache=True)
def _sample_remainder(rows, n, s, full, maxd, mins, j, samples, threads, seed):
    """Uniform j-sets: histogram over d_E of the uncorrectable sets that contain
    no listed minimal set, and the number of all uncorrectable sets seen."""
    t = mins.shape[0]
    words = mins.shape[1]
    hist = np.zeros((threads, maxd + 1), dtype=np.int64)
    seen = np.zeros(threads, dtype=np.int64)
    per = samples // threads
    for th in prange(threads):
        np.random.seed(seed + 7919 * th + 104729 * j)
        mask = np.zeros(rows.shape[1], dtype=np.uint64)
        work = np.zeros_like(rows)
        erased = np.zeros(n, dtype=np.uint8)
        emask = np.zeros(words, dtype=np.uint64)
        perm = np.arange(n)
        for _ in range(per):
            for i in range(n):
                erased[i] = 0
            for i in range(j):
                r = i + np.random.randint(0, n - i)
                tmp = perm[i]
                perm[i] = perm[r]
                perm[r] = tmp
                erased[perm[i]] = 1
            d = exponent(rows, n, s, erased, mask, full, work)
            if d == 0:
                continue
            seen[th] += 1
            for w in range(words):
                emask[w] = 0
            for i in range(n):
                if erased[i]:
                    emask[i // 64] |= np.uint64(1) << np.uint64(i % 64)
            listed = False
            for l in range(t):
                inside = True
                for w in range(words):
                    if mins[l, w] & ~emask[w]:
                        inside = False
                        break
                if inside:
                    listed = True
                    break
            if not listed:
                hist[th, d] += 1
    return hist.sum(axis=0), seen.sum(), per * threads


REMAINDER_FLOOR = 3.0  # no event in M samples: the 95% upper bound on the rate is 3/M


def stratified_layer(code, mins, j, kl_samples, samples, max_samples, tol, threads=8, seed=1):
    """b_j and u_j as (sets containing a listed minimal set) + (remainder).

    The first part is the Karp-Luby estimate over the listed sets; the remainder
    is sampled uniformly. Its standard error is never taken below
    REMAINDER_FLOOR / M for M samples, so that a layer with no remainder event
    carries the 95% upper bound 3/M on the remainder as its error. The first
    batch has the size at which that floor meets the tolerance; the sample is
    then doubled until the combined relative standard error of b_j is at most
    `tol` or `max_samples` is reached.
    """
    kl = karp_luby_layer(code, mins, j, kl_samples, threads, seed)
    rows, n = pack_rows(code.h), code.n
    masks = _masks(mins, n)
    hist = np.zeros(2 * code.k + 1, dtype=np.float64)
    total, seen, rounds = 0, 0, 0
    batch = samples
    if kl["b"][0] > 0:
        batch = int(min(max_samples, max(samples, 1.05 * REMAINDER_FLOOR / (tol * kl["b"][0]))))
    while True:
        h, sn, cnt = _sample_remainder(rows, n, code.s, full_mask(n), 2 * code.k, masks, j,
                                       batch, threads, seed + 500 * rounds)
        hist += h
        total += cnt
        seen += sn
        rounds += 1
        d = np.arange(len(hist))
        out = {}
        for key, g in (("b", 1 - 2.0 ** (-d)), ("u", (d > 0).astype(float))):
            mean = float((hist * g).sum() / total)
            var = max(float((hist * g * g).sum() / total) - mean * mean, 0.0) / total
            out[key] = (mean, max(var ** 0.5, REMAINDER_FLOOR / total))
        b = kl["b"][0] + out["b"][0]
        se = (kl["b"][1] ** 2 + out["b"][1] ** 2) ** 0.5
        if b > 0 and se / b <= tol:
            break
        if total >= max_samples:
            break
        batch = int(min(total, max_samples - total))
        if batch < threads:
            break
    return {"kl": kl, "remainder": out, "remainder_events": int(hist.sum()),
            "remainder_floor": REMAINDER_FLOOR,
            "uncorrectable_seen": int(seen), "samples": int(total),
            "b": (b, se),
            "u": (kl["u"][0] + out["u"][0], (kl["u"][1] ** 2 + out["u"][1] ** 2) ** 0.5)}


# ------------------------------------------------------------------ driver

def run(name, max_size, samples=20_000_000, kl_samples=400_000, threads=8, seed=1,
        sat_time=3600.0, max_count=2_000_000, log=print, target_events=2500,
        max_samples=4_000_000_000, check_samples=2_000_000):
    code = qec_codes.get(name)
    n, k = code.n, code.k
    tol = target_events ** -0.5
    log(f"{code.name}: n={n} k={k} nnz={code.nnz}")
    start = time.time()
    (HERE / "results").mkdir(exist_ok=True)
    mins, w = minimal_sets(code, max_size, max_count=max_count, time_limit=sat_time, log=log,
                           cache=HERE / "results" / f"minimal_{name}.json", name=name)
    sat_seconds = time.time() - start
    by_size = {}
    for m in mins:
        by_size[len(m)] = by_size.get(len(m), 0) + 1
    distance = min(by_size) if by_size else None
    log(f"  minimal sets by size: {by_size}; complete through size {w}; distance {distance}")
    layers = []
    for j in range(n + 1):
        row = {"j": j}
        if j <= w:
            row["kl"] = (exact_first_layer(code, mins, j) if j == distance
                         else karp_luby_layer(code, mins, j, kl_samples, threads, seed))
        if n - j <= w:  # dual side: complements of size n - j
            row["kl_dual"] = (exact_first_layer(code, mins, n - j) if n - j == distance
                              else karp_luby_layer(code, mins, n - j, kl_samples, threads, seed + 1))
        if "kl" in row or "kl_dual" in row:  # sampling only as a cross-check
            row["mc"] = sampled_layer(code, j, min(samples, check_samples), threads, seed)
        else:
            row["mc"] = sampled_layer(code, j, samples, threads, seed)
            mean, se = row["mc"]["b"]
            if mins and (mean <= 0 or se / mean > tol):
                # too few uncorrectable sets seen: listed union + sampled remainder
                row["strat"] = stratified_layer(code, mins, j, kl_samples, samples, max_samples,
                                                tol, threads, seed)
            fmean, fse = row["mc"]["f"]
            if fmean > 0 and fse / fmean > tol:  # fidelity side: enlarge the plain sample
                row["mc"] = sampled_layer(code, j, samples, threads, seed,
                                          target_events=target_events, max_samples=max_samples)
        layers.append(row)
        note = (f" stratified: samples={row['strat']['samples']} "
                f"remainder_events={row['strat']['remainder_events']}" if "strat" in row else "")
        log(f"  layer {j:3d} done ({time.time() - start:.0f}s) "
            f"samples={row['mc']['samples']} events={row['mc']['events']}{note}")
    out = {"code": code.name, "key": name, "n": n, "k": k, "nnz": code.nnz,
           "distance": distance, "complete_level": w, "minimal_by_size": by_size,
           "samples": samples, "kl_samples": kl_samples, "sat_seconds": sat_seconds,
           "threads": threads, "tolerance": tol, "max_samples": max_samples,
           "remainder_floor": REMAINDER_FLOOR,
           "wall_seconds": time.time() - start, "layers": layers}
    path = HERE / "results" / f"hybrid_{name}.json"
    path.write_text(json.dumps(out, indent=1))
    log(f"wrote {path.name}: wall {out['wall_seconds']:.0f}s")
    return out


def patch_leading(name, log=print):
    """Replace the sampled estimate of the first nonzero layer of an existing
    result file by the exact finite sum over the cached minimal sets."""
    path = HERE / "results" / f"hybrid_{name}.json"
    out = json.loads(path.read_text())
    data = json.loads((HERE / "results" / f"minimal_{name}.json").read_text())
    mins = [tuple(m) for m in data["sets"]]
    code = qec_codes.get(name)
    n, d = code.n, out["distance"]
    assert data["complete"] >= d and min(len(m) for m in mins) == d
    exact = exact_first_layer(code, mins, d)
    for row in out["layers"]:
        if row["j"] == d:
            log(f"  {name} j={d}: b {row['kl']['b']} -> {exact['b']}, classes {exact['by_exponent']}")
            row["kl"] = exact
        if n - row["j"] == d:
            row["kl_dual"] = exact
    path.write_text(json.dumps(out, indent=1))
    return exact


def resplit(name, threads=8, seed=1, log=print):
    """Recompute the split layers of an existing result file with the current
    remainder rule, from the cached minimal sets. Other layers are untouched."""
    path = HERE / "results" / f"hybrid_{name}.json"
    out = json.loads(path.read_text())
    data = json.loads((HERE / "results" / f"minimal_{name}.json").read_text())
    mins = [tuple(m) for m in data["sets"]]
    assert data["complete"] == out["complete_level"]
    code = qec_codes.get(name)
    start = time.time()
    for row in out["layers"]:
        if "strat" in row:
            row["strat"] = stratified_layer(code, mins, row["j"], out["kl_samples"],
                                            out["samples"], out["max_samples"],
                                            out["tolerance"], threads, seed)
            st = row["strat"]
            log(f"  {name} layer {row['j']:3d} resplit ({time.time() - start:.0f}s): "
                f"samples={st['samples']} remainder_events={st['remainder_events']} "
                f"rel.se={st['b'][1] / st['b'][0]:.4f}")
            path.write_text(json.dumps(out, indent=1))
    out["remainder_floor"] = REMAINDER_FLOOR
    path.write_text(json.dumps(out, indent=1))


def combine(result):
    """One estimate per layer, with relative standard errors on each scale.

    Returns lists f, b, u, the relative standard errors and the source of each layer.
    """
    k = result["k"]
    f, b, u, rf, rb, ru, src = [], [], [], [], [], [], []
    for row in result["layers"]:
        mc = row["mc"]
        bj, sb = mc["b"]
        uj, su = mc["u"]
        fj, sf = mc["f"]
        source = "sampling"
        if "strat" in row:  # listed union + sampled remainder
            bj, sb = row["strat"]["b"]
            uj, su = row["strat"]["u"]
            fj, sf = 1 - bj, sb
            source = "minimal sets + remainder"
        if "kl" in row:  # exact union structure: use it for the infidelity side
            bj, sb = row["kl"]["b"]
            uj, su = row["kl"]["u"]
            fj, sf = 1 - bj, sb
            source = "minimal sets"
        if "kl_dual" in row and "kl" not in row:
            dual, sd = row["kl_dual"]["dual"]
            fj, sf = (1 + dual) / 4 ** k, sd / 4 ** k
            bj, sb = 1 - fj, sf
            source = "minimal sets (dual)"
        f.append(fj); b.append(bj); u.append(uj)
        rf.append(sf / fj if fj > 0 else 0.0)
        rb.append(sb / bj if bj > 0 else 0.0)
        ru.append(su / uj if uj > 0 else 0.0)
        src.append(source)
    return {"f": f, "b": b, "u": u, "rel_f": rf, "rel_b": rb, "rel_u": ru, "source": src}


